// English currency names come from the browser's ICU data (Intl.DisplayNames), so no name table to maintain.
const displayNames = new Intl.DisplayNames(["en"], { type: "currency" });

/** English name of a currency code (e.g. "EUR" -> "Euro"); falls back to the code if unknown. */
export function currencyName(code: string): string {
  try {
    return displayNames.of(code) ?? code;
  } catch {
    return code;
  }
}

/** Every currency with its English name, ready to render in a select. */
export const CURRENCIES = CURRENCY_CODES.map((code) => ({ code, name: currencyName(code) }));
